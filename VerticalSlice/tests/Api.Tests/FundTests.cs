    [Test]
    public async Task Periodicity_Round_Trips_As_Enum_Name()
    {
        var client = Factory.CreateClient();

        var created = await client.PostAsync(
            "/api/funds",
            new StringContent(
                """{"name": "Alpha", "periodicity": "Monthly"}""",
                Encoding.UTF8,
                "application/json"
            )
        );
        await Assert.That(created.StatusCode).IsEqualTo(HttpStatusCode.Created);
        var publicId = (await created.Content.ReadFromJsonAsync<CreateFund.Response>())!.PublicId;

        // Read the raw column, bypassing the EF converter. A schema name cannot be a SQL
        // parameter, and SchemaName is generated by the test base, not user input.
        await using var dbContext = CreateDbContext();
#pragma warning disable EF1003
        var stored = await dbContext
            .Database.SqlQueryRaw<string>(
                "SELECT periodicity AS [Value] FROM [" + SchemaName + "].[funds] WHERE public_id = {0}",
                publicId
            )
            .SingleAsync();
#pragma warning restore EF1003
        await Assert.That(stored).IsEqualTo("Monthly");

        var fetched = await client.GetAsync($"/api/funds/{publicId}");
        await Assert
            .That(await fetched.Content.ReadAsStringAsync())
            .Contains("\"periodicity\":\"Monthly\"");
        var body = await fetched.Content.ReadFromJsonAsync<GetFund.Response>();
        await Assert.That(body!.Periodicity).IsEqualTo(Periodicity.Monthly);
    }

